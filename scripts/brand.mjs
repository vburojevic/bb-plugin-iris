#!/usr/bin/env node
// Generates Iris's brand files from one shape: an iris of four blades whose
// opening is a square window, the place where UI appears. One color always:
// bb draws the mask icon in its own color, the logos come in a light and a
// dark ink, and the in-app mark wears the theme's accent.
// Run: node scripts/brand.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = (f, s) => fs.writeFileSync(path.join(root, f), `${s.trim()}\n`);

const P = (v) => +v.toFixed(3);
const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const add = (a, b) => [a[0] + b[0], a[1] + b[1]];
const mul = (a, s) => [a[0] * s, a[1] * s];
const norm = (a) => mul(a, 1 / Math.hypot(a[0], a[1]));
const cross = (a, b) => a[0] * b[1] - a[1] * b[0];
const meet = (p, d, q, e) => add(p, mul(d, cross(sub(q, p), e) / cross(d, e)));
function onCircle(p, d, c, R) {
  const f = sub(p, c);
  const b = f[0] * d[0] + f[1] * d[1];
  return add(p, mul(d, -b + Math.sqrt(b * b - (f[0] ** 2 + f[1] ** 2 - R * R))));
}

/**
 * n straight-edged blades tiling a disc of radius R around a regular n-gon
 * opening of circumradius r. Each blade runs along one side of the opening and
 * on to the rim; neighbors are separated by a gap of the given width.
 */
export function aperture({ cx = 32, cy = 32, R = 29, r = 14, n = 4, gap = 3.2, rot = -45 } = {}) {
  const c = [cx, cy];
  const V = Array.from({ length: n }, (_, k) => {
    const a = ((rot + (k * 360) / n) * Math.PI) / 180;
    return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
  });
  const dir = V.map((v, k) => norm(sub(V[(k + 1) % n], v)));
  let d = "";
  for (let k = 0; k < n; k++) {
    const a = dir[k];
    const b = dir[(k - 1 + n) % n];
    const inside = add(V[k], mul(norm(add(a, b)), 2));
    const shift = (p, u) => {
      let nn = [-u[1], u[0]];
      if ((inside[0] - p[0]) * nn[0] + (inside[1] - p[1]) * nn[1] < 0) nn = mul(nn, -1);
      return add(p, mul(nn, gap / 2));
    };
    const pa = shift(V[k], a);
    const pb = shift(V[k], b);
    const apex = meet(pa, a, pb, b);
    const A = onCircle(pa, a, c, R);
    const B = onCircle(pb, b, c, R);
    const ang = (q) => (Math.atan2(q[1] - cy, q[0] - cx) * 180) / Math.PI;
    const sweep = (ang(B) - ang(A) + 720) % 360 < 180 ? 1 : 0;
    d += `M${P(apex[0])} ${P(apex[1])}L${P(A[0])} ${P(A[1])}A${R} ${R} 0 0 ${sweep} ${P(B[0])} ${P(B[1])}Z`;
  }
  return d;
}

export const MARK = aperture();

export function mark(ink, size = 64) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 64 64">
  <title>Iris</title>
  <path fill="${ink}" d="${MARK}"/>
</svg>`;
}

out("assets/icon.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><path d="${MARK}"/></svg>`);
out("assets/logo-dark.svg", mark("#F2F2F5", 256));
out("assets/logo-light.svg", mark("#17171C", 256));
out(
  "ui/brand-mark.ts",
  `// Generated by scripts/brand.mjs: the Iris mark's path in a 64 by 64 box.\nexport const MARK_PATH = "${MARK}";`,
);
console.log("wrote assets/icon.svg, assets/logo-light.svg, assets/logo-dark.svg, ui/brand-mark.ts");
